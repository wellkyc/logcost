package suggest

import (
	"fmt"
	"io"
	"strings"
)

func split(list []Suggestion) (drops, samples []Suggestion) {
	for _, s := range list {
		if s.Action == Sample {
			samples = append(samples, s)
		} else {
			drops = append(drops, s)
		}
	}
	return drops, samples
}

func vrlMatch(list []Suggestion) string {
	parts := make([]string, len(list))
	for i, s := range list {
		parts[i] = "match(msg, r'" + s.Pattern + "')"
	}
	return strings.Join(parts, " || ")
}

func Vector(w io.Writer, list []Suggestion, version string) error {
	drops, samples := split(list)
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by logcost %s, replace your_source with your source or transform\n", version)
	if len(list) == 0 {
		b.WriteString("# nothing to filter, logcost has no suggestions for these logs\n")
		_, err := io.WriteString(w, b.String())
		return err
	}
	b.WriteString("transforms:\n")
	input := "your_source"
	if len(drops) > 0 {
		b.WriteString("  logcost_drop:\n")
		b.WriteString("    type: filter\n")
		fmt.Fprintf(&b, "    inputs: [%s]\n", input)
		b.WriteString("    condition: |-\n")
		b.WriteString("      msg = to_string(.message) ?? \"\"\n")
		fmt.Fprintf(&b, "      !(%s)\n", vrlMatch(drops))
		input = "logcost_drop"
	}
	if len(samples) > 0 {
		b.WriteString("  logcost_sample:\n")
		b.WriteString("    type: sample\n")
		fmt.Fprintf(&b, "    inputs: [%s]\n", input)
		fmt.Fprintf(&b, "    rate: %d\n", SampleRate)
		b.WriteString("    exclude: |-\n")
		b.WriteString("      msg = to_string(.message) ?? \"\"\n")
		fmt.Fprintf(&b, "      !(%s)\n", vrlMatch(samples))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func FluentBit(w io.Writer, list []Suggestion, version string) error {
	drops, samples := split(list)
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by logcost %s, set Match to your input tag and the key to the field with the log line\n", version)
	if len(samples) > 0 {
		fmt.Fprintf(&b, "# Fluent Bit can't sample single lines, so %d sampling suggestion(s) are left out\n", len(samples))
	}
	if len(drops) == 0 {
		b.WriteString("# nothing to filter, logcost has no drop suggestions for these logs\n")
	}
	for _, s := range drops {
		b.WriteString("[FILTER]\n")
		b.WriteString("    Name    grep\n")
		b.WriteString("    Match   *\n")
		fmt.Fprintf(&b, "    Exclude log %s\n", s.Pattern)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func ottlString(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	return strings.ReplaceAll(s, `"`, `\"`)
}

func OTel(w io.Writer, list []Suggestion, version string) error {
	drops, samples := split(list)
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by logcost %s, add filter/logcost to the processors of your logs pipeline\n", version)
	if len(samples) > 0 {
		fmt.Fprintf(&b, "# sampling by pattern is not supported by the filter processor, %d sampling suggestion(s) are left out\n", len(samples))
	}
	if len(drops) == 0 {
		b.WriteString("# nothing to filter, logcost has no drop suggestions for these logs\n")
		_, err := io.WriteString(w, b.String())
		return err
	}
	b.WriteString("processors:\n")
	b.WriteString("  filter/logcost:\n")
	b.WriteString("    error_mode: ignore\n")
	b.WriteString("    logs:\n")
	b.WriteString("      log_record:\n")
	for _, s := range drops {
		fmt.Fprintf(&b, "        - 'IsMatch(body, \"%s\")'\n", ottlString(s.Pattern))
	}
	_, err := io.WriteString(w, b.String())
	return err
}
